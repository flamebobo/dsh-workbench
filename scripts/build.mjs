// Bundles host/ -> dsh-plugin/index.js (ESM, Node) and ui/ -> dsh-plugin/client.js (DSH browser module format).
import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'

const pkg = JSON.parse(readFileSync('dsh-plugin/package.json', 'utf8'))

await build({
  entryPoints: ['host/index.ts'], outfile: 'dsh-plugin/index.js', bundle: true,
  platform: 'node', format: 'esm', target: 'node22', logLevel: 'info',
  banner: { js: '// Generated by scripts/build.mjs from host/ and core/. Do not edit.' },
  define: { __WB_VERSION__: JSON.stringify(pkg.version) },
})

const ui = await build({
  entryPoints: ['ui/main.tsx'], bundle: true, write: false, format: 'iife', globalName: 'WB',
  platform: 'browser', target: 'es2022', jsx: 'transform', external: ['react', 'react-dom'], logLevel: 'info',
  define: { __WB_VERSION__: JSON.stringify(pkg.version) },
})
writeFileSync('dsh-plugin/client.js',
  `// Generated by scripts/build.mjs from ui/. Do not edit.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(pkg.name)},\n  factory(require) {\n${ui.outputFiles[0].text}\n    return WB;\n  },\n});\n`)
