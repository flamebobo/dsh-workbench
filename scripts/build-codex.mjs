// Builds the Codex plugin into codex-plugin/: server.mjs (codex/main.ts with core and the MCP SDK, one ESM file for Node) and
// board.html (ui/codex.tsx with React, one self-contained MCP App page), plus the example skill pack next to them.
import { build } from 'esbuild'
import { cpSync, readFileSync, writeFileSync } from 'node:fs'

const plugin = JSON.parse(readFileSync('codex-plugin/plugin.json', 'utf8'))
const define = { __WB_VERSION__: JSON.stringify(plugin.version), __WB_HOST__: JSON.stringify('codex') }

await build({
  entryPoints: ['codex/main.ts'], outfile: 'codex-plugin/server.mjs', bundle: true,
  platform: 'node', format: 'esm', target: 'node20', logLevel: 'info', define,
  // bundled CommonJS dependencies call require() for Node built-ins
  banner: { js: "// Generated by scripts/build-codex.mjs from codex/ and core/. Do not edit.\nimport { createRequire as __wbRequire } from 'node:module';\nconst require = __wbRequire(import.meta.url);" },
})

const ui = await build({
  entryPoints: ['ui/codex.tsx'], bundle: true, write: false, format: 'iife', minify: true,
  platform: 'browser', target: 'es2022', jsx: 'transform', logLevel: 'info', define: { ...define, 'process.env.NODE_ENV': '"production"' },
})
const script = ui.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')

// DSH supplies its theme tokens (--dsw-alias-*); in Codex the page defines them, light and dark (theme from the host context).
const tokens = {
  light: { 'label-primary': '#1a1a1a', 'label-secondary': '#555', 'label-tertiary': '#888', 'bg-base': '#fff', 'bg-layer-1': '#f6f7f9', 'bg-layer-2': '#eef0f3', 'border-l1': '#eceef1', 'border-l2': '#e3e5e8', 'interactive-bg-hover': '#f0f2f5', link: '#2f6bff', 'state-business-primary': '#2f6bff', 'state-error-primary': '#e5484d', 'state-success-primary': '#2da44e', 'state-warn-primary': '#d98a00' },
  dark: { 'label-primary': '#ececec', 'label-secondary': '#b4b4b4', 'label-tertiary': '#8a8a8a', 'bg-base': '#181818', 'bg-layer-1': '#212121', 'bg-layer-2': '#2a2a2a', 'border-l1': '#2c2c2c', 'border-l2': '#383838', 'interactive-bg-hover': '#2a2a2a', link: '#6b9bff', 'state-business-primary': '#5b8cff', 'state-error-primary': '#ff6b6b', 'state-success-primary': '#46c46b', 'state-warn-primary': '#f0a92e' },
}
const vars = (t) => Object.entries(t).map(([k, v]) => `--dsw-alias-${k}:${v}`).join(';')
writeFileSync('codex-plugin/board.html', `<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>研发工作台</title>
<!-- Generated by scripts/build-codex.mjs from ui/. Do not edit. -->
<style>:root{color-scheme:light;${vars(tokens.light)}}:root[data-theme=dark]{color-scheme:dark;${vars(tokens.dark)}}
html,body,#root{height:100%;margin:0}body{background:var(--dsw-alias-bg-base);color:var(--dsw-alias-label-primary);font-family:-apple-system,BlinkMacSystemFont,"PingFang SC","Microsoft YaHei",sans-serif}</style>
</head><body><div id="root"></div><script>${script}</script></body></html>
`)
cpSync('dsh-plugin/examples', 'codex-plugin/examples', { recursive: true })
